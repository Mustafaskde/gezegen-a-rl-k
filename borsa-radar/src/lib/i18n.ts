const dictionaries: Record<Language, Record<TranslationKey, string>> = { tr, en };

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

export const eventKey = (e: EventType) => `event.${e}` as TranslationKey;
export const sectorKey = (s: Sector) => `sector.${s}` as TranslationKey;
export const sessionKey = (s: Session) => `session.${s}` as TranslationKey;
export const sentimentKey = (s: Sentiment) => `sentiment.${s}` as TranslationKey;
